using System.Buffers.Text;
using System.Security.Cryptography;
using System.Text;
using BudTack.Identity.Api.Contracts;
using BudTack.Identity.Internal.Domain;
using Microsoft.Extensions.Logging;

namespace BudTack.Identity.Internal.Application;

/// <summary>
/// HU-10 and ADR-010: the single-use links that activate an account or reset its
/// password. The token leaves once, in the response; only its hash is stored, and
/// nobody but the person holding the link ever handles a password.
/// </summary>
internal sealed partial class AccountLinks(
    IUsersRepository users, IAccountTokensRepository tokens, PasswordHasher hasher, TimeProvider clock, ILogger<AccountLinks> logger)
{
    public static readonly TimeSpan ActivationLifetime = TimeSpan.FromHours(72);
    public static readonly TimeSpan ResetLifetime = TimeSpan.FromMinutes(30);

    private const int TokenBytes = 32;

    /// <summary>For a new account, or one still pending.</summary>
    public Task<AccountLink> IssueActivationAsync(Guid actor, Guid userId, CancellationToken cancellationToken) =>
        IssueAsync(actor, userId, AccountToken.Activation, ActivationLifetime, cancellationToken);

    public async Task<AccountLink> CreateActivationAsync(Guid actor, Guid userId, CancellationToken cancellationToken)
    {
        var user = await RequireAsync(userId, cancellationToken).ConfigureAwait(false);
        if (user.Status != AccountStatus.Pending)
        {
            throw new AccountStateConflictException("The account is already active.");
        }

        return await IssueActivationAsync(actor, userId, cancellationToken).ConfigureAwait(false);
    }

    public async Task<AccountLink> CreatePasswordResetAsync(Guid actor, Guid userId, CancellationToken cancellationToken)
    {
        var user = await RequireAsync(userId, cancellationToken).ConfigureAwait(false);
        if (user.Status != AccountStatus.Active)
        {
            throw new AccountStateConflictException("The account is not active yet; it needs an activation link.");
        }

        return await IssueAsync(actor, userId, AccountToken.PasswordReset, ResetLifetime, cancellationToken).ConfigureAwait(false);
    }

    public async Task ConfirmAsync(LinkConfirmation request, CancellationToken cancellationToken)
    {
        var (token, password) = AccountRules.Validate(request);

        if (!await tokens.ConfirmAsync(HashOf(token), hasher.Hash(password), clock.GetUtcNow(), cancellationToken).ConfigureAwait(false))
        {
            LogRefused(logger);
            throw new IdentityValidationException([new FieldError("token", AccountRules.InvalidLink)]);
        }
    }

    private async Task<Domain.User> RequireAsync(Guid userId, CancellationToken cancellationToken) =>
        await users.FindByIdAsync(userId, cancellationToken).ConfigureAwait(false) ?? throw new UserNotFoundException();

    private async Task<AccountLink> IssueAsync(
        Guid actor, Guid userId, string purpose, TimeSpan lifetime, CancellationToken cancellationToken)
    {
        var token = Base64Url.EncodeToString(RandomNumberGenerator.GetBytes(TokenBytes));
        var expiresAt = clock.GetUtcNow() + lifetime;

        await tokens.ReplaceAsync(
            new AccountToken(Guid.CreateVersion7(), userId, purpose, HashOf(token), expiresAt, actor),
            cancellationToken).ConfigureAwait(false);

        LogIssued(logger, purpose, userId, actor);
        return new AccountLink(token, expiresAt);
    }

    internal static string HashOf(string token) =>
        Convert.ToHexStringLower(SHA256.HashData(Encoding.UTF8.GetBytes(token)));

    [LoggerMessage(Level = LogLevel.Information, Message = "A {Purpose} link for account {UserId} was generated by {Actor}")]
    private static partial void LogIssued(ILogger logger, string purpose, Guid userId, Guid actor);

    [LoggerMessage(Level = LogLevel.Warning, Message = "An account link was refused: unknown, expired or used")]
    private static partial void LogRefused(ILogger logger);
}
